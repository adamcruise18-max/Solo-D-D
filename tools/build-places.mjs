// Converts the OpenStreetMap place list (CSV) into the game places file.
// Data © OpenStreetMap contributors, ODbL. Run: npm run places
import { readFileSync, writeFileSync } from 'node:fs';

const CAT = {
  'shop=supermarket': 'supermarket', 'shop=convenience': 'convenience', 'amenity=fuel': 'gas',
  'amenity=pharmacy': 'pharmacy', 'amenity=clinic': 'clinic', 'amenity=hospital': 'hospital',
  'shop=hardware': 'hardware', 'shop=doityourself': 'hardware', 'shop=outdoor': 'outdoor',
  'amenity=fire_station': 'fire',
};
const PLAIN = {
  supermarket: 'Grocery store', convenience: 'Corner store', gas: 'Gas station', pharmacy: 'Pharmacy',
  clinic: 'Clinic', hospital: 'Hospital', hardware: 'Hardware store', outdoor: 'Outdoor store', fire: 'Fire station',
};

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') q = false;
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.length > 1) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const [header, ...rows] = parseCsv(readFileSync(process.argv[2] || 'data/poi-15mi-97078.csv', 'utf8'));
const idx = Object.fromEntries(header.map((h, i) => [h, i]));
const out = [];
const seen = [];
for (const r of rows) {
  const cat = CAT[r[idx.osm_tag]];
  if (!cat) continue;
  const lat = +r[idx.lat], lon = +r[idx.lon];
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  const name = (r[idx.name] || r[idx.brand] || '').trim() || PLAIN[cat];
  // Merge duplicates: same category and name within about 40 m.
  if (seen.some((s) => s.cat === cat && s.name === name && Math.abs(s.lat - lat) < 0.0004 && Math.abs(s.lon - lon) < 0.0005)) continue;
  const m = /openstreetmap\.org\/(node|way|relation)\/(\d+)/.exec(r[idx.osm_url] || '');
  const id = m ? `${m[1][0]}${m[2]}` : `x${out.length}`;
  const p = { id, name, cat, lat: +lat.toFixed(6), lon: +lon.toFixed(6) };
  seen.push(p);
  out.push(p);
}
const js = `// Generated by tools/build-places.mjs from OpenStreetMap data.\n// © OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright)\nwindow.LL_PLACES = ${JSON.stringify(out)};\n`;
writeFileSync(process.argv[3] || 'docs/data/places.js', js);
console.log(`Wrote ${out.length} places`);
